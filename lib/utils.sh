#!/usr/bin/env bash
#===============================================================================
# SysGuardian
# Shared Utility Functions
#===============================================================================

set -euo pipefail

#===============================================================================
# PROTEÇÃO CONTRA CARREGAMENTO MÚLTIPLO
#===============================================================================

if [[ -n "${SYSGUARDIAN_UTILS_LOADED:-}" ]]; then
    return 0 2>/dev/null
fi

readonly SYSGUARDIAN_UTILS_LOADED=1

#===============================================================================
# COMANDOS
#===============================================================================

command_exists() {

    command -v "$1" >/dev/null 2>&1

}

#===============================================================================
# ARQUIVOS
#===============================================================================

directory_exists() {

    [[ -d "$1" ]]

}

file_exists() {

    [[ -f "$1" ]]

}
